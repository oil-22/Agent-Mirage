def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def save(p,v):
    with p.open('x',encoding='utf8')as f:json.dump(v,f,ensure_ascii=False,indent=2);f.write('\n')
def one(text,old,new):
    assert text.count(old)==1,old[:100]
    return text.replace(old,new)

def main():
    assert not RUNTIME.exists()
    shutil.copytree(BOUNDED/'runtime-package',RUNTIME,ignore=shutil.ignore_patterns('__pycache__','*.pyc','control-inputs','controls-plan.json','manifest.json','private.token'))
    # Original matched actor body and queue, with genuinely new trajectory IDs.
    shutil.copy2(PARENT/'runtime-package/actor-template.json',RUNTIME/'actor-template.json')
    shutil.copy2(HERE/'bounded_auxiliary.py',RUNTIME/'bounded_auxiliary.py')
    launcher=RUNTIME/'launch_gui_service_once.py'
    launcher.write_text(launcher.read_text(encoding='utf8').replace('full-gui-single-evidence-20261108-01',HERE.name),encoding='utf8',newline='\n')
    server=RUNTIME/'gpu_server.py';original=server.read_text(encoding='utf8');text=original
    text=one(text,"sys.path[:0]=[str(HERE),str(HERE/'release')]","sys.path[:0]=[str(HERE),str(HERE/'release'),str(HERE/'grammar-vendor')]")
    text=one(text,"        audit=runtime['audited_generation']","        audit=runtime['audited_generation']\n        import bounded_auxiliary\n        bounded_data=bounded_auxiliary.prepare(aux_processor,generation,root,package)")
    start=text.index('                        from PIL import Image\n')
    end=text.index('                    else:\n                        with audit(engine.model',start)
    replacement='''                        text,actual,utf8_roundtrip=bounded_auxiliary.generate(aux_model,aux_processor,generation,torch,audit,bounded_data,raw_image,folder)
                        envelope={'request_sha256':digest(canonical(payload)),'image_sha256':payload['image_sha256'],
                                  'model':payload['model'],'revision':payload['revision'],'raw_output':text,'natural_eos':actual['natural_EOS']}
                        if not utf8_roundtrip:
                            # Do not edit raw output/EOS. The original observer
                            # rejects the extra transport-error field wholesale.
                            envelope['evidence_transport_error']='Native generated bytes fail strict UTF8 roundtrip'
                        result={'evidence_response':envelope}
                        try:
                            if not utf8_roundtrip:raise contract.EvidenceContractError('Invalid native UTF8; entire packet withheld')
                            save(folder/'evidence-packet.json',contract.actor_packet(payload,text,actual['natural_EOS']))
                        except contract.EvidenceContractError as exc:
                            save(folder/'contract-failure.json',{'type':type(exc).__name__,'message':str(exc),'no_retry':True})
'''
    text=text[:start]+replacement+text[end:]
    # This span includes both actual main actor and judge calls, byte-for-byte.
    main_start="                    else:\n                        with audit(engine.model"
    main_end="                    response.update(result,operation=op"
    assert original[original.index(main_start):original.index(main_end)]==text[text.index(main_start):text.index(main_end)]
    server.write_text(text,encoding='utf8',newline='\n')
    (HERE/'GPU-server-diff.txt').write_text(''.join(difflib.unified_diff(original.splitlines(True),text.splitlines(True),fromfile='prior server',tofile='new bounded auxiliary server')),encoding='utf8')
    plan=json.loads((PARENT/'runtime-package/plan.json').read_bytes())
    for row in plan['queue']:row['run_id']=row['run_id'].replace('single9b-fullgui-20261108-01','bounded9b-fullgui-20261109-03')
    plan.update(policy='single-image-neutral-evidence-v5-schema-constrained-development',
        stage='new_matched_full_GUI_development_after_source_controls',authorization='User sustained goal: 做实验做到防御有效果为止',
        evidence_contract_sha256=sha(RUNTIME/'release/image_evidence.py'),primary_core_sha256=sha(RUNTIME/'release/defense/core.py'),
        old_absence_and_readiness_failures_unresolved=True,
        repairs='Exact candidate quote spans and conservative bounded-uncertainty routing from repair01; auxiliary structural mask and impossible literal-range withholding from bounded02',
        auxiliary_mask_changes_decoding=True,completed_prior_trajectories_not_resumed=True,
        source_condition_tradeoff='New prompts and lexical scope routing may miss or misclassify assertions; structural auxiliary decoding can change facts. Full original main inputs/strict validator/actions/budgets retained. Packet unavailable never automatically allows or blocks.',
        formal_efficacy_established=False)
    save(RUNTIME/'plan.json',plan)
    save(RUNTIME/'auxiliary-config.json',{'model':plan['auxiliary_single_model'],'only_current_full_image_and_fixed_prompt':True,
        'max_calls_per_trajectory':60,'no_retry':True,'auxiliary_structural_mask':True})
    for p in RUNTIME.rglob('*.py'):ast.parse(p.read_text(encoding='utf8'),filename=str(p))
